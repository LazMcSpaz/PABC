// What is actually in this game, generated from the engine.
//
//   node scripts/whats-in-the-game.mjs > docs/whats-in-the-game.md
//
// WHY THIS IS GENERATED AND NOT WRITTEN. There are 51 player-facing verbs, 103
// events and 361 tunables, and 1,384 lines of design notes written for whoever
// was building it rather than for whoever plays it. A hand-written inventory of
// that would be wrong within a week — and being wrong is worse than being
// absent, because a player who catches the manual lying stops trusting it.
//
// So the NUMBERS are pulled live from a booted game and the PROSE is curated.
// That split is deliberate: numbers are where drift actually hurts (a tutorial
// that says a courtship costs 10 Sway when it costs 6 is teaching a lie), and
// prose is where a generator produces unreadable sludge.
//
// The verb explanations are not written here at all. `availableVerbsAgainst`
// in the adapter already computes, live and per-faction, a player-language
// account of every diplomacy verb — what it costs, what it does, and why it is
// greyed out. That text has existed for a while and has never been collected
// anywhere a person could read it end to end. This collects it.
import { createGame } from "../src/game/setup.js";
import { startTurn } from "../src/game/turn.js";
import { adaptState } from "../src/prototype/engineAdapter.js";
import { CONFIG } from "../src/game/config.js";
import { CHIPS } from "../src/game/content.js";

const g = createGame({
  seed: 424242,
  factionIds: ["versari", "goldgrass", "lakers", "plainers"],
  humanFactionId: "versari",
  minors: ["croppers"],
  mapSize: "medium",
});
startTurn(g);
const view = adaptState(g, "versari");
const dip = view.diplomacy;

const out = [];
const say = (s = "") => out.push(s);

say("# What is in this game");
say();
say("*Generated by `node scripts/whats-in-the-game.mjs`. Every number below is");
say("read from the live engine, so it cannot drift out of date — if a value here");
say("is wrong, the game is wrong. Regenerate after any rules change.*");
say();

// --- the one condition -------------------------------------------------
say("## The only way to win");
say();
say("**Dominion.** Every surviving faction is your **ally**, your **vassal**, or");
say("**gone** — held for " + CONFIG.victory.holdRounds + " consecutive rounds. Minors count.");
say();
say("There is no second victory condition. No score race, no VP threshold you can");
say("cross by building quietly. Three faces, one condition, and the interesting");
say("games are the mixed ones.");
say();
say("Everything below exists to give you a way to move a faction into one of");
say("those three columns, or to stop somebody else doing it.");
say();

// --- the currencies ----------------------------------------------------
say("## The three things you spend");
say();
say("| | what it buys | where it comes from |");
say("|---|---|---|");
say("| **Scrap** | what a faction *has* — units, chips, rushes | Location output |");
say("| **Sway** | what a faction *thinks* — courtship, gifts, espionage | floor " +
  CONFIG.sway.floor + " + dominated hexes + agreements |");
// `baseActions` really is 0: there is no player-wide pool. Every Action comes
// from a Location you hold — which is why losing cities costs you TEMPO and
// not just income, and it is the single most commonly missed rule in the game.
say("| **Actions** | what you can do this turn | one per Location you hold, plus chips |");
say();
say("**Actions come from ground.** There is no player-wide pool — you get one per");
say("Location you hold. Losing a city costs you tempo, not only income, and that");
say("is the rule most often missed.");
say();
say("**Nothing converts.** A mountain of scrap buys no goodwill, and no amount of");
say("Sway builds a unit. That wall is the whole reason the political game is a");
say("game rather than a shop.");
say();
say("Sway is a **flow, not a war chest**: it caps at " + CONFIG.sway.cap +
  " and income above that is wasted.");
say("The floor of " + CONFIG.sway.floor + " buys exactly one courtship (" +
  CONFIG.sway.courtUpkeep + " a round), always, for everybody — a second one has to");
say("be paid for out of ground or agreements.");
say();

// --- reputation --------------------------------------------------------
const D = CONFIG.diplomacy;
say("## The three things people think of you");
say();
say("| | scope | moves when |");
say("|---|---|---|");
say("| **Standing** | one pair, both directions separately | you deal, gift, court, trespass, attack |");
say("| **Menace** | global — everybody sees it | you attack, declare unprovoked, get caught lying |");
say("| **Honor** | global | you keep or break your word |");
say();
say("Standing runs " + D.standingMin + " to " + D.standingMax +
  ". A pact needs **+" + D.pactStandingReq + " both ways**.");
say();
say("Menace decays " + D.menace.decayPerRound + " a round on its own. Honor recovers " +
  D.honor.decayPerRound + " a round toward " + D.honor.decayToward +
  " — so a bad stretch is survivable, but it takes real rounds of clean play.");
say();
say("**Menace is witness-gated.** Striking somebody where nobody can see costs you");
say("less than doing it in the open. That is not an oversight — it is why");
say("espionage exists.");
say();

// --- the verbs, straight from the engine -------------------------------
say("## Every verb you have, and what it costs");
say();
say("*This table is the adapter's own text, live. It is what the game will tell");
say("you when you hover the button, so if it reads oddly here it reads oddly");
say("there too.*");
say();
say("### Toward another faction");
say();
const f = dip.factions.find((x) => x.id === "lakers");
say("| verb | what it does |");
say("|---|---|");
for (const v of f.verbs) {
  const text = (v.outcome || v.reason || "").replace(/\|/g, "\\|");
  say(`| \`${v.verb}\` | ${text} |`);
}
say();

// Verbs the per-faction list cannot show, because they are not aimed at a
// faction or need a live object to exist first.
say("### Things you do to the board, or to yourself");
say();
say("| verb | what it does |");
say("|---|---|");
const BOARD = [
  ["move / contest", "The army. Contesting a Location takes it; contesting a unit is a raid."],
  ["recruit / reinforce", `A unit costs ${CONFIG.unitRecruitCost} scrap. Reinforcing in the field walks to you over rounds.`],
  ["build / upgrade / rush", "Chips into a Location's slots. An upgrade replaces a chip in its own slot."],
  ["set-slider", "How much of a Location's output feeds construction against the bank."],
  ["build-post", `A Listening Post: ${CONFIG.posts.buildCost} scrap, ${CONFIG.posts.upkeep} upkeep, radius-${CONFIG.posts.range} vision. Concealed until found.`],
  ["build-blockade", "Choke a road. Costs the victim output; pays you nothing."],
  ["sabotage", "Intelligence B2. Drops a rival Location's Loyalty by 1, once a round."],
  ["declare-position", `Say something to the whole board and be held to it. Up to ${D.positions.max} at once.`],
  ["expose / forge / fabricate", `Espionage, ${CONFIG.sway.opCost} Sway each. See below.`],
  ["counter-offer", "Haggle an offer on your table instead of taking it or leaving it."],
];
for (const [verb, text] of BOARD) say(`| \`${verb}\` | ${text} |`);
say();

// --- the concepts that are not verbs -----------------------------------
say("## The parts that are not buttons");
say();
say("These are the rules that run whether you press anything or not. They are");
say("the ones most likely to surprise you.");
say();

say("### Loyalty → Influence → Zone of Control");
say();
say("A Location's Loyalty projects an influence field. Where your field beats");
say("everyone else's, the ground is yours. **Dominance is a step function with a");
say("wide dead zone** — measured on the real board:");
say();
say("| your projection | hexes you dominate |");
say("|---|---|");
say("| under 6 | 1 |");
say("| 6 to under 12 | 7 |");
say("| 12 or more | 19 |");
say();
say("So Loyalty 4 through 8 changes nothing on a bare Location, and buying");
say("influence chips can buy you *zero* extra hexes. The heatmap draws a hard");
say("amber ring at the threshold precisely because this cliff is invisible");
say("otherwise — walk that ring to see what one more point would buy.");
say();

say("### What territory costs you");
say();
say("| | cost |");
say("|---|---|");
say(`| Crossing a rival's zone | +${CONFIG.influence.zocMoveCost} movement per hex |`);
say(`| Holding a surviving faction's homeland you took | ${CONFIG.sway.occupation} Sway a round, each |`);
say(`| …and if you cannot pay | Standing with them, at ${CONFIG.sway.arrearsStandingPer} per unpaid point |`);
say(`| Chips past your first ${CONFIG.economy.freeChips} | ${CONFIG.economy.perExtraChip} scrap a round each |`);
say(`| Buying far from your holdings | arrives late — never refused |`);
say();
say("Occupation is the keystone: **conquest and courtship compete for the same");
say("pool.** Taking somebody's homeland does not just anger them, it eats the");
say("capacity you would have used to talk to anybody else.");
say();
say("If you are down to " + CONFIG.sway.occupierFloor + " Location you are not an occupier, you are cornered —");
say("occupation stops charging. That exists so a bad position is recoverable.");
say();

say("### Courtship — the only road to an alliance");
say();
say("You cannot buy a pact. The road is: **court** → state a condition drawn from");
say("what they actually want → they watch you keep it → Standing rises → the pact");
say("becomes possible at +" + D.pactStandingReq + ".");
say();
say(`A courtship costs ${CONFIG.sway.courtUpkeep} Sway every round it runs and lapses if you cannot pay.`);
say(`You may open ${D.posture.initiativesPerRound} a round — but how many you RUN at once is your budget's`);
say("decision, not a rule.");
say();
say("Every faction has **six possible wants**: a homeland somebody else holds,");
say("amends for a wrong, help in a war they are losing, a trade route, your");
say("columns off their ground, somebody's lead cut down. What they want decides");
say("what the courtship asks of you — and it changes what they will *pay* for in");
say("a deal.");
say();

say("### Coalitions — and what stops them being unfair");
say();
say("The board can rise against a leader. It needs **grounds**, and leading is not");
say("grounds:");
say();
say("- **menace** — Menace at " + D.coalition.menaceGrounds + " or above, which you earned");
say("- **grievance** — somebody can name a specific thing you did");
say("- **fear** — a lead past " + D.coalition.fearThreshold + " over your *strongest rival*, which is rare");
say();
say("A spotless faction that is simply winning does not get ganged up on. Members");
say("decide individually, liking you holds them back, and a draft cools a partner");
say("to Wary rather than making them an enemy. **Making your own peace is how you");
say("leave a rising.**");
say();

say("### Espionage");
say();
say("Three ops, " + CONFIG.sway.opCost + " Sway each. They differ in whether the claim is *true* and in");
say("*who it is about*:");
say();
say("| op | the claim | can it rebound? |");
say("|---|---|---|");
say("| **Expose** | a true wrong of theirs that nobody saw | no — you are publishing, not lying |");
say("| **Forge** | a false wrong, done by them to somebody else | yes |");
say("| **Fabricate** | a false wrong, done by them to *you* | yes |");
say();
say("**Expose needs ears.** You can only publish what your apparatus could have");
say("learned: Intelligence B1 (a network, hears anywhere), a live Listening Post");
say("in range, or Intelligence A1 with eyes on the place. A dormant post hears");
say("nothing.");
say();
say("Both lies roll against **your Honor as cover** and **their");
say("counter-intelligence as the counter** — so a spotless name is genuinely");
say("useful for lying, and a rival's Spy Ring genuinely protects them. Caught");
say(`costs ${CONFIG.sway.ops.caughtHonorLoss} Honor, ${CONFIG.sway.ops.caughtMenace} Menace, and a grievance to everyone the lie touched.`);
say();
say(`Sabotage is a covert act too: traced, it costs ${CONFIG.sway.ops.sabotageCaughtHonorLoss} Honor and they learn it was you.`);
say();

say("### Positions — the only thing you can say for free");
say();
say("Every other political act is a transaction. A **position** is unilateral and");
say("public: *I will make no war on the Croppers*, said to nobody in particular.");
say();
say("Keeping one costs nothing. Breaking one costs " + D.positions.breakHonorLoss +
  " Honor (an ordinary broken");
say("promise costs " + D.honor.breakLoss + "), " + D.positions.breakMenace + " Menace, and a grievance — and the board will");
say("**name it back at you, in the words you used**, for " + D.positions.citeWithinRounds + " rounds. That citation");
say("is the entire point.");
say();
say("Standing down honestly costs " + D.positions.withdrawHonorLoss + ", and you cannot do it inside " +
  D.positions.minRounds + " rounds.");
say();

// --- the numbers appendix ---------------------------------------------
say("## Numbers worth knowing");
say();
say("| | |");
say("|---|---|");
say("| Actions a round | one per Location held (no player-wide pool) |");
say(`| A unit costs | ${CONFIG.unitRecruitCost} scrap |`);
say(`| Pact needs | +${D.pactStandingReq} Standing both ways |`);
say(`| Courtship upkeep | ${CONFIG.sway.courtUpkeep} Sway a round |`);
say(`| A gift | ${CONFIG.sway.perStanding} Sway per point, with diminishing returns |`);
say(`| An espionage op | ${CONFIG.sway.opCost} Sway |`);
say(`| Sway ceiling | ${CONFIG.sway.cap} |`);
say(`| Surprise attack | −${D.honor.surpriseAttackLoss} Honor |`);
say(`| Unprovoked declaration | +${D.menace.declareUnjustified} Menace |`);
say(`| Dominion hold | ${CONFIG.victory.holdRounds} consecutive rounds |`);
say(`| Authored chips | ${Object.keys(CHIPS).length} |`);
say();

console.log(out.join("\n"));
